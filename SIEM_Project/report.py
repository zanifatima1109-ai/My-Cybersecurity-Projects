from pathlib import Path
from html import escape

PROJECT_DIR = Path.home() / "SIEM_Project"
ALERT_FILE = PROJECT_DIR / "alerts.log"
REPORT_FILE = PROJECT_DIR / "security_report.html"


def generate_report():
    if ALERT_FILE.exists():
        alerts = [
            line.strip()
            for line in ALERT_FILE.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]
    else:
        alerts = []

    rows = ""

    for alert in alerts:
        rows += f"<tr><td>{escape(alert)}</td></tr>\n"

    if not rows:
        rows = "<tr><td>No security alerts found.</td></tr>"

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Mini SIEM Security Report</title>
    <style>
        body {{
            font-family: Arial, sans-serif;
            background: #eef2f7;
            margin: 0;
            padding: 30px;
        }}
        .container {{
            max-width: 900px;
            margin: auto;
            background: white;
            padding: 25px;
            border-radius: 12px;
        }}
        h1 {{ color: #12345a; }}
        .card {{
            background: #fff0f0;
            padding: 15px;
            border-left: 5px solid #d93025;
            margin: 20px 0;
        }}
        table {{
            width: 100%;
            border-collapse: collapse;
        }}
        th, td {{
            border: 1px solid #ddd;
            padding: 12px;
            text-align: left;
            overflow-wrap: anywhere;
        }}
        th {{
            background: #12345a;
            color: white;
        }}
    </style>
</head>
<body>
    <div class="container">
        <h1>Mini SIEM Security Report</h1>
        <p>Project: Security Log Monitoring System</p>

        <div class="card">
            <h2>Total Security Alerts: {len(alerts)}</h2>
            <p>Report generated by Python.</p>
        </div>

        <h2>Security Alert Details</h2>
        <table>
            <tr><th>Alert Information</th></tr>
            {rows}
        </table>
    </div>
</body>
</html>
"""

    REPORT_FILE.write_text(html, encoding="utf-8")

    print("HTML report created successfully!")
    print("Report location:", REPORT_FILE)
    print("Total alerts:", len(alerts))


if __name__ == "__main__":
    generate_report()

